def secret(m, x, y, w=6, h=3):
    """A hidden room: a stone shell with s cells inside and shards; the fake wall is the s bounding box."""
    m.rect(x, y - 1, w + 1, h + 2, 'X')      # floor, roof and back wall; the left side is the way in
    m.rect(x, y, w, h, 's')
    for k in range(1, w - 1, 2):
        m.set(x + k, y, '*')


